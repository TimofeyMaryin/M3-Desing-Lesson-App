        Одной из самых мощных функций Material Theme 3 является возможность настройки цветовой схемы приложения на основе цветов обоев пользователя. Это происходит благодаря новой системе динамической цветовой палитры. Если раньше разработчикам приходилось задавать цвета вручную, то теперь система предлагает цвета автоматически, улучшая визуальное восприятие приложения.

        Для начала работы с динамическими цветами в Jetpack Compose, можно использовать компонент `dynamicLightColorScheme()` или `dynamicDarkColorScheme()` в зависимости от темы устройства. Эти функции автоматически подстраиваются под тему и цветовую палитру устройства, улучшая визуальное единство.

        Вот пример использования динамических цветов:
        ```kotlin
        val colors = if (isSystemInDarkTheme()) {
            dynamicDarkColorScheme(context)
        } else {
            dynamicLightColorScheme(context)
        }

        MaterialTheme(
            colorScheme = colors,
            typography = Typography,
            content = {
                // Контент приложения
            }
        )
        ```

        Используя Material Theme 3, разработчики могут легко улучшить взаимодействие с пользователями, предоставляя уникальный дизайн под каждого.
